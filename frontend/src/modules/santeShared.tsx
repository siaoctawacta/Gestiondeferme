export type HealthActType = 'VACCINATION' | 'TRAITEMENT' | 'DESINFECTION' | 'DIAGNOSTIC';
/** `EN_RETARD` is derived by the API (planned and dated before today), never stored. */
export type HealthActStatus = 'PLANIFIE' | 'REALISE' | 'EN_RETARD' | 'ANNULE';
export type TargetKind = 'LOT' | 'ANIMAL' | 'BATIMENT';

/** `GET /health-acts`: one act, with exactly one of `batchId`, `animalId`, `buildingId` set. */
export interface HealthActRow {
  id: string;
  /** `YYYY-MM-DD` (planned date, or the day it was done when entered as done) */
  date: string;
  /** Lot code, animal tag or building name. */
  target: string;
  targetKind: TargetKind;
  batchId: string | null;
  animalId: string | null;
  buildingId: string | null;
  type: HealthActType;
  productName: string | null;
  /** Veterinary stock article the act draws on (category MEDICAMENT or VACCIN). */
  stockItemId: string | null;
  dose: string | null;
  /** Quantity of the stock article consumed (done acts with a stock article). */
  quantity: number | null;
  durationDays: number | null;
  withdrawalDays: number | null;
  veterinarian: string | null;
  symptoms: string | null;
  diagnosis: string | null;
  status: HealthActStatus;
  /** Set when the act was generated by applying a vaccination plan to a lot. */
  planId: string | null;
  note: string | null;
  /** `YYYY-MM-DD`: end of the withdrawal period this act causes (done treatments). */
  withdrawalUntil: string | null;
}

