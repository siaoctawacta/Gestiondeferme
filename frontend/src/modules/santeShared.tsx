export const ACT_TYPES: { value: HealthActType; label: string }[] = [
  { value: 'VACCINATION', label: 'Vaccination' },
  { value: 'TRAITEMENT', label: 'Traitement' },
  { value: 'DESINFECTION', label: 'Désinfection' },
  { value: 'DIAGNOSTIC', label: 'Diagnostic' },
];
export const actTypeLabel = (t: string) => ACT_TYPES.find((x) => x.value === t)?.label ?? t;

export const ACT_STATUSES: StatusDef[] = [
  { value: 'PLANIFIE', label: 'Planifié', tone: 'warning' },
  { value: 'REALISE', label: 'Réalisé', tone: 'success' },
  { value: 'EN_RETARD', label: 'En retard', tone: 'danger' },
  { value: 'ANNULE', label: 'Annulé', tone: 'neutral' },
];

export const SEVERITIES: { value: Severity; label: string; tone: PillTone }[] = [
  { value: 'FAIBLE', label: 'Faible', tone: 'neutral' },
  { value: 'MOYENNE', label: 'Moyenne', tone: 'warning' },
  { value: 'GRAVE', label: 'Grave', tone: 'danger' },
];

export const LOG_TYPES: { value: BiosecurityType; label: string }[] = [
  { value: 'NETTOYAGE', label: 'Nettoyage' },
  { value: 'DESINFECTION', label: 'Désinfection' },
  { value: 'PEDILUVE', label: 'Pédiluve' },
  { value: 'VISITEUR', label: 'Visiteur' },
];

/** A planned act due within this many days (today included) is flagged `À faire`. */
export const DUE_SOON_DAYS = 7;

const addDays = (iso: string, days: number) => new Date(new Date(iso).getTime() + days * 86400000).toISOString().slice(0, 10);

/**
 * How pressing a planned act is: `En retard` once its date is before today, `À faire` within a week, else plain
 * `Planifié`. Nothing for a done or cancelled act. Dates are calendar dates compared in UTC, like the API.
 */
export function dueState(date: string, status: HealthActStatus): { label: string; tone: PillTone } | null {
  if (status !== 'PLANIFIE' && status !== 'EN_RETARD') return null;
  const today = todayIso();
  if (date < today) return { label: 'En retard', tone: 'danger' };
  if (date <= addDays(today, DUE_SOON_DAYS)) return { label: 'À faire', tone: 'warning' };
  return { label: 'Planifié', tone: 'neutral' };
}

/** Under withdrawal until the end of `until` (the last day included). */
export const underWithdrawal = (until: string | null | undefined): until is string => Boolean(until) && until! >= todayIso();

/** The notice shown under the header of a lot or an animal still under a withdrawal period. */
export function WithdrawalNotice({ until }: { until: string | null | undefined }) {
  if (!underWithdrawal(until)) return null;
  return (
    <div className="mb-4">
      <Pill tone="danger">{`Délai d'attente jusqu'au ${formatDate(until)}`}</Pill>
    </div>
  );
}

type Values = Record<string, unknown>;

/* ------------------------------------------ targets ------------------------------------------ */

const KIND_OPTIONS: { value: 'LOT' | 'ANIMAL'; label: string }[] = [{ value: 'LOT', label: 'Lot' }, { value: 'ANIMAL', label: 'Animal' }];

/**
 * What the user may pick as a target, as the production modules do: poultry lots with read rights on `lots`, pig
 * lots and animals with read rights on `porcs` (the API checks the species module too). Never asks for what the
 * user cannot read.
 */
export function useTargets(enabled = true) {
  const { can } = useAuth();
  const poultry = can('lots', 'read');
  const pigs = can('porcs', 'read');
  const avianLots = useEndpointOptions({ endpoint: '/batches', labelKey: 'code', params: { species: 'AVICOLE', status: 'EN_COURS' } }, undefined, enabled && poultry);
  const pigLots = useEndpointOptions({ endpoint: '/batches', labelKey: 'code', params: { species: 'PORCIN', status: 'EN_COURS' } }, undefined, enabled && pigs);
  const animals = useEndpointOptions({ endpoint: '/animals', labelKey: 'tag', params: { status: 'ACTIF' } }, undefined, enabled && pigs);
  const buildings = useEndpointOptions({ endpoint: '/buildings' }, undefined, enabled);
  const kinds = KIND_OPTIONS.filter((k) => (k.value === 'LOT' ? poultry || pigs : pigs));
  return { kinds, lots: [...avianLots, ...pigLots], animals, buildings };
}

export type Targets = ReturnType<typeof useTargets>;

/** The `Lot | Animal` choice and the select of that kind (`batchId` / `animalId` of the payload). */
export function lotOrAnimalFields(values: Values, targets: Targets): Field[] {
  const kind = String(values.targetKind ?? targets.kinds[0]?.value ?? 'LOT');
  return [
    { name: 'targetKind', label: 'Type de cible', type: 'segmented', only: 'create', defaultValue: targets.kinds[0]?.value, options: targets.kinds },
    kind === 'ANIMAL'
      ? { name: 'animalId', label: 'Animal', type: 'select', required: true, only: 'create', options: targets.animals }
      : { name: 'batchId', label: 'Lot', type: 'select', required: true, only: 'create', options: targets.lots },
  ];
}

/** The chosen lot or animal as payload keys. */
export function lotOrAnimalPayload(values: Values, targets: Targets): Values {
  const kind = String(values.targetKind ?? targets.kinds[0]?.value ?? 'LOT');
  return kind === 'ANIMAL' ? { animalId: values.animalId } : { batchId: values.batchId };
}

/* -------------------------------------------- acts -------------------------------------------- */

const STOCK_CATEGORY: Partial<Record<HealthActType, string>> = { VACCINATION: 'VACCIN', TRAITEMENT: 'MEDICAMENT' };
/** One form field per category: a product picked for a vaccine does not follow a change of type. */
const ITEM_FIELD: Partial<Record<HealthActType, string>> = { VACCINATION: 'vaccinItemId', TRAITEMENT: 'medicamentItemId' };

/** Batches in stock of an article, as select options (`lot (quantity)`); shares the cache of the item page. */
export function useBatchOptions(itemId: string): Option[] {
  const { data } = useFarmQuery<StockItemDetailData>(['/stock', 'detail', itemId], () => api.get<StockItemDetailData>(`/stock/${itemId}`), {
    enabled: itemId !== '',
  });
  return (data?.batches ?? [])
    .filter((b) => b.quantity > 0)
    .map((b) => ({ value: b.id, label: `${b.lotNumber ?? 'Sans n°'} (${formatNumber(b.quantity)})` }));
}

const quantityField = (): Field => ({ name: 'quantity', label: 'Quantité', type: 'number', required: true, min: 0.01, step: 0.01 });

type ActFormProps = { row?: HealthActRow; scope?: Record<string, string>; onSaved: () => void; onClose: () => void };

/**
 * Add / edit a health act. The type and, when creating, the status (planned or done) are segmented choices; the
 * target is a lot or an animal (a building for a disinfection), or fixed by the scope inside a lot or animal page.
 * A done vaccination or treatment may draw on a veterinary stock article (quantity and product batch, the API
 * takes FEFO when no batch is given): its refusals (`Stock insuffisant`, `Lot périmé`) show in the dialog. An
 * existing act keeps its type, target and stock article.
 */
export function ActForm({ row, scope, onSaved, onClose }: ActFormProps) {
  const targets = useTargets(!row && !scope);
  const [pickedItem, setPickedItem] = useState('');
  const batches = useBatchOptions(pickedItem);
  const itemOf = (v: Values) => {
    const field = ITEM_FIELD[(v.type ?? 'VACCINATION') as HealthActType];
    return field ? String(v[field] ?? '') : '';
  };

  const fields = (v: Values): Field[] => {
    const type = row?.type ?? ((v.type ?? 'VACCINATION') as HealthActType);
    const done = row ? row.status === 'REALISE' : (v.status ?? 'REALISE') === 'REALISE';
    const itemField = ITEM_FIELD[type];
    const stockItemId = row ? row.stockItemId : itemOf(v);
    const withStock = Boolean(stockItemId);
    const clinical = type === 'TRAITEMENT' || type === 'DIAGNOSTIC';
    return [
      { name: 'type', label: 'Type', type: 'segmented', only: 'create', required: true, defaultValue: 'VACCINATION', options: ACT_TYPES },
      {
        name: 'status', label: 'Statut', type: 'segmented', only: 'create', required: true, defaultValue: 'REALISE',
        options: [{ value: 'PLANIFIE', label: 'Planifié' }, { value: 'REALISE', label: 'Réalisé' }],
      },
      ...(row || scope
        ? []
        : type === 'DESINFECTION'
          ? [{ name: 'buildingId', label: 'Bâtiment', type: 'select', required: true, only: 'create', options: targets.buildings } as Field]
          : lotOrAnimalFields(v, targets)),
      { name: 'date', label: 'Date', type: 'date', required: true, defaultValue: todayIso },
      ...(itemField && !row
        ? [{
            name: itemField, label: 'Produit en stock', type: 'select', only: 'create',
            options: { endpoint: '/stock-items', params: { active: 'true', category: STOCK_CATEGORY[type]! } },
          } as Field]
        : []),
      ...(withStock ? [] : [{ name: 'productName', label: 'Produit (texte libre)', type: 'text' } as Field]),
      { name: 'dose', label: 'Dose', type: 'text' },
      ...(withStock && done ? [quantityField()] : []),
      ...(withStock && done && !row
        ? [{ name: 'stockBatchId', label: 'Lot de produit', type: 'select', only: 'create', options: batches } as Field]
        : []),
      ...(type === 'TRAITEMENT'
        ? [
            { name: 'durationDays', label: 'Durée (jours)', type: 'number', min: 0, step: 1 } as Field,
            { name: 'withdrawalDays', label: "Délai d'attente (jours)", type: 'number', min: 0, step: 1 } as Field,
          ]
        : []),
      { name: 'veterinarian', label: 'Vétérinaire', type: 'text' },
      ...(clinical ? [{ name: 'symptoms', label: 'Symptômes', type: 'textarea' } as Field, { name: 'diagnosis', label: 'Diagnostic', type: 'textarea' } as Field] : []),
      { name: 'note', label: 'Note', type: 'text' },
    ];
  };

  const toPayload = (v: Values, mode: FormMode): Values => {
    const type = row?.type ?? ((v.type ?? 'VACCINATION') as HealthActType);
    const done = row ? row.status === 'REALISE' : (v.status ?? 'REALISE') === 'REALISE';
    const stockItemId = row ? row.stockItemId ?? '' : itemOf(v);
    const clinical = type === 'TRAITEMENT' || type === 'DIAGNOSTIC';
    const body: Values = {
      date: v.date,
      productName: stockItemId ? '' : text(v.productName),
      dose: text(v.dose),
      quantity: stockItemId && done ? num(v.quantity) : '',
      durationDays: type === 'TRAITEMENT' ? num(v.durationDays) : '',
      withdrawalDays: type === 'TRAITEMENT' ? num(v.withdrawalDays) : '',
      veterinarian: text(v.veterinarian),
      symptoms: clinical ? text(v.symptoms) : '',
      diagnosis: clinical ? text(v.diagnosis) : '',
      note: text(v.note),
    };
    if (mode === 'update') return body;
    return {
      ...body,
      type,
      status: v.status ?? 'REALISE',
      ...(scope ?? (type === 'DESINFECTION' ? { buildingId: v.buildingId } : lotOrAnimalPayload(v, targets))),
      stockItemId,
      stockBatchId: stockItemId && done ? v.stockBatchId : '',
    };
  };

  return (
    <ActionDialog
      title={`${row ? 'Modifier' : 'Ajouter'} — Santé`}
      mode={row ? 'update' : 'create'}
      initial={row as unknown as Values | undefined}
      fields={fields}
      onValues={(v) => setPickedItem(row ? '' : itemOf(v))}
      toPayload={toPayload}
      onSubmit={(body) => (row ? api.patch(`/health-acts/${row.id}`, body) : api.post('/health-acts', body))}
      onClose={onClose}
      onDone={onSaved}
    />
  );
}

type RowDialogProps<T> = { row: T; onClose: () => void; onDone: () => void };

/** `Marquer réalisé`: the day it was done and, for an act on a stock article, the quantity and product batch. */
export function CompleteActDialog({ row, onClose, onDone }: RowDialogProps<HealthActRow>) {
  const batches = useBatchOptions(row.stockItemId ?? '');
  const withStock = Boolean(row.stockItemId);
  return (
    <ActionDialog
      title={`Marquer réalisé — ${row.target}`}
      intro={[actTypeLabel(row.type), row.productName].filter(Boolean).join(' · ')}
      initial={{ quantity: row.quantity }}
      fields={[
        { name: 'doneDate', label: 'Date de réalisation', type: 'date', required: true, defaultValue: todayIso },
        ...(withStock
          ? [quantityField(), { name: 'stockBatchId', label: 'Lot de produit', type: 'select', options: batches } as Field]
          : []),
      ]}
      onSubmit={(body) => api.post(`/health-acts/${row.id}/complete`, body)}
      onClose={onClose}
      onDone={onDone}
    />
  );
}

/** `Annuler`: a planned act is dropped; a done one also gives its stock back (the API reverses by source). */
export const CancelActDialog = ({ row, onClose, onDone }: RowDialogProps<HealthActRow>) => (
  <ConfirmDialog
    title="Annuler l'intervention"
    message={`Annuler l'intervention du ${row.date} sur ${row.target} ?${row.status === 'REALISE' ? ' Le stock consommé sera restitué.' : ''}`}
    confirmLabel="Annuler l'intervention"
    onClose={onClose}
    onConfirm={async () => {
      await api.post(`/health-acts/${row.id}/cancel`);
      onDone();
    }}
  />
);

